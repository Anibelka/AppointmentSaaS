create table if not exists public.businesses (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  name text not null,
  phone text,
  address text,
  timezone text not null default 'America/Santo_Domingo',
  subscription_plan text not null default 'Pro' check (subscription_plan in ('Básico','Pro')),
  trial_days integer not null default 30 check (trial_days >= 0),
  notification_immediate boolean not null default true,
  notification_24h boolean not null default true,
  notification_2h boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  role text not null default 'client' check (role in ('admin','employee','client')),
  business_id uuid references public.businesses(id) on delete set null,
  staff_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  name text not null,
  price numeric(10,2) not null check (price >= 0),
  duration_minutes integer not null check (duration_minutes between 5 and 720),
  description text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id, name)
);

create table if not exists public.staff (
  id bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  user_id uuid unique references auth.users(id) on delete set null,
  name text not null,
  specialty text not null default '',
  schedule_label text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (business_id, name)
);

alter table public.profiles
  drop constraint if exists profiles_staff_id_fkey;
alter table public.profiles
  add constraint profiles_staff_id_fkey foreign key (staff_id) references public.staff(id) on delete set null;

create table if not exists public.business_hours (
  business_id uuid not null references public.businesses(id) on delete cascade,
  day_of_week smallint not null check (day_of_week between 0 and 6),
  is_open boolean not null default false,
  opening_time time not null default '09:00',
  closing_time time not null default '17:00',
  primary key (business_id, day_of_week),
  check (not is_open or opening_time < closing_time)
);

create table if not exists public.business_closures (
  id bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  closure_date date not null,
  reason text not null,
  created_at timestamptz not null default now(),
  unique (business_id, closure_date)
);

create table if not exists public.appointments (
  id bigint generated by default as identity primary key,
  business_id uuid not null references public.businesses(id) on delete cascade,
  client_id uuid references auth.users(id) on delete set null,
  client_name text not null,
  client_phone text not null,
  client_email text not null,
  service_id bigint not null references public.services(id),
  staff_id bigint not null references public.staff(id),
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  local_date date not null,
  local_time time not null,
  status text not null default 'Pendiente' check (status in ('Pendiente','Confirmada','Completada','Cancelada','No asistió')),
  source text not null default 'Cliente' check (source in ('Cliente','Negocio')),
  notes text not null default '',
  reminder_status text not null default 'Programado' check (reminder_status in ('Programado','Enviado','Cancelado','Error')),
  email_status text not null default 'Pendiente' check (email_status in ('Pendiente','Enviado','Error','No configurado')),
  email_sent_at timestamptz,
  confirmation_code text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (ends_at > starts_at)
);

-- Prevent overlapping active appointments for the same professional.
do $$
begin
  if not exists (
    select 1 from pg_constraint where conname = 'appointments_no_staff_overlap'
  ) then
    alter table public.appointments
      add constraint appointments_no_staff_overlap
      exclude using gist (
        staff_id with =,
        tstzrange(starts_at, ends_at, '[)') with &&
      )
      where (status not in ('Cancelada','No asistió'));
  end if;
end $$;

