create or replace function public.book_appointment(
  p_business_slug text,
  p_service_id bigint,
  p_staff_id bigint,
  p_starts_at timestamptz,
  p_notes text default ''
)
returns public.appointments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business public.businesses%rowtype;
  v_service public.services%rowtype;
  v_staff public.staff%rowtype;
  v_profile public.profiles%rowtype;
  v_email text;
  v_local_start timestamp;
  v_local_end timestamp;
  v_day smallint;
  v_hours public.business_hours%rowtype;
  v_ends_at timestamptz;
  v_code text;
  v_row public.appointments%rowtype;
begin
  if auth.uid() is null then
    raise exception 'Debes iniciar sesión para reservar.' using errcode = '42501';
  end if;

  select * into v_business from public.businesses where slug = p_business_slug;
  if not found then raise exception 'Negocio no encontrado.'; end if;

  select * into v_profile from public.profiles where id = auth.uid();
  select email into v_email from auth.users where id = auth.uid();

  select * into v_service from public.services
  where id = p_service_id and business_id = v_business.id and active;
  if not found then raise exception 'Servicio no disponible.'; end if;

  select * into v_staff from public.staff
  where id = p_staff_id and business_id = v_business.id and active;
  if not found then raise exception 'Profesional no disponible.'; end if;

  if p_starts_at <= now() then
    raise exception 'No se puede reservar una hora que ya pasó.';
  end if;

  v_ends_at := p_starts_at + make_interval(mins => v_service.duration_minutes);
  v_local_start := p_starts_at at time zone v_business.timezone;
  v_local_end := v_ends_at at time zone v_business.timezone;
  v_day := extract(dow from v_local_start)::smallint;

  if exists (
    select 1 from public.business_closures
    where business_id = v_business.id and closure_date = v_local_start::date
  ) then
    raise exception 'El negocio está cerrado en la fecha seleccionada.';
  end if;

  select * into v_hours from public.business_hours
  where business_id = v_business.id and day_of_week = v_day;

  if not found or not v_hours.is_open then
    raise exception 'El negocio no trabaja ese día.';
  end if;

  if v_local_start::time < v_hours.opening_time
     or v_local_end::date <> v_local_start::date
     or v_local_end::time > v_hours.closing_time then
    raise exception 'La cita queda fuera del horario del negocio.';
  end if;

  if exists (
    select 1 from public.appointments a
    where a.staff_id = p_staff_id
      and a.status not in ('Cancelada','No asistió')
      and tstzrange(a.starts_at, a.ends_at, '[)') && tstzrange(p_starts_at, v_ends_at, '[)')
  ) then
    raise exception 'El horario ya no está disponible.';
  end if;

  v_code := 'APT-' || upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 10));

  insert into public.appointments (
    business_id, client_id, client_name, client_phone, client_email,
    service_id, staff_id, starts_at, ends_at, local_date, local_time,
    status, source, notes, confirmation_code
  ) values (
    v_business.id, auth.uid(), coalesce(nullif(v_profile.full_name,''), split_part(v_email,'@',1)),
    coalesce(v_profile.phone,''), v_email, p_service_id, p_staff_id,
    p_starts_at, v_ends_at, v_local_start::date, v_local_start::time,
    'Confirmada', 'Cliente', coalesce(p_notes,''), v_code
  ) returning * into v_row;

  perform public.write_audit(v_business.id, 'Cita ' || v_code || ' creada desde el portal del cliente');
  return v_row;
exception
  when exclusion_violation then
    raise exception 'El horario acaba de ser ocupado. Selecciona otro.';
end;
$$;

create or replace function public.admin_create_appointment(
  p_service_id bigint,
  p_staff_id bigint,
  p_starts_at timestamptz,
  p_client_name text,
  p_client_phone text,
  p_client_email text,
  p_notes text default ''
)
returns public.appointments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business public.businesses%rowtype;
  v_service public.services%rowtype;
  v_staff public.staff%rowtype;
  v_local_start timestamp;
  v_local_end timestamp;
  v_day smallint;
  v_hours public.business_hours%rowtype;
  v_ends_at timestamptz;
  v_code text;
  v_row public.appointments%rowtype;
begin
  select b.* into v_business from public.businesses b
  where b.id = public.current_business_id() and public.current_profile_role() = 'admin';
  if not found then raise exception 'Acceso administrativo requerido.' using errcode = '42501'; end if;

  select * into v_service from public.services where id=p_service_id and business_id=v_business.id and active;
  if not found then raise exception 'Servicio no disponible.'; end if;
  select * into v_staff from public.staff where id=p_staff_id and business_id=v_business.id and active;
  if not found then raise exception 'Profesional no disponible.'; end if;
  if p_starts_at <= now() then raise exception 'No se puede agendar en el pasado.'; end if;

  v_ends_at := p_starts_at + make_interval(mins => v_service.duration_minutes);
  v_local_start := p_starts_at at time zone v_business.timezone;
  v_local_end := v_ends_at at time zone v_business.timezone;
  v_day := extract(dow from v_local_start)::smallint;

  if exists (select 1 from public.business_closures where business_id=v_business.id and closure_date=v_local_start::date) then
    raise exception 'El negocio está cerrado en esa fecha.';
  end if;
  select * into v_hours from public.business_hours where business_id=v_business.id and day_of_week=v_day;
  if not found or not v_hours.is_open then raise exception 'El negocio no trabaja ese día.'; end if;
  if v_local_start::time < v_hours.opening_time or v_local_end::date<>v_local_start::date or v_local_end::time>v_hours.closing_time then
    raise exception 'La cita queda fuera del horario del negocio.';
  end if;
  if exists (
    select 1 from public.appointments a where a.staff_id=p_staff_id
      and a.status not in ('Cancelada','No asistió')
      and tstzrange(a.starts_at,a.ends_at,'[)') && tstzrange(p_starts_at,v_ends_at,'[)')
  ) then raise exception 'El profesional ya tiene una cita en ese horario.'; end if;

  v_code := 'APT-' || upper(substr(encode(gen_random_bytes(8), 'hex'), 1, 10));
  insert into public.appointments (
    business_id, client_id, client_name, client_phone, client_email,
    service_id, staff_id, starts_at, ends_at, local_date, local_time,
    status, source, notes, confirmation_code
  ) values (
    v_business.id, null, trim(p_client_name), trim(p_client_phone), lower(trim(p_client_email)),
    p_service_id, p_staff_id, p_starts_at, v_ends_at, v_local_start::date, v_local_start::time,
    'Pendiente', 'Negocio', coalesce(p_notes,''), v_code
  ) returning * into v_row;

  perform public.write_audit(v_business.id, 'Cita ' || v_code || ' creada manualmente');
  return v_row;
exception
  when exclusion_violation then raise exception 'El horario acaba de ser ocupado.';
end;
$$;

create or replace function public.set_appointment_status(p_appointment_id bigint, p_status text)
returns public.appointments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.appointments%rowtype;
begin
  if p_status not in ('Pendiente','Confirmada','Completada','Cancelada','No asistió') then
    raise exception 'Estado inválido.';
  end if;

  select * into v_row from public.appointments where id=p_appointment_id;
  if not found then raise exception 'Cita no encontrada.'; end if;

  if not public.is_business_admin(v_row.business_id) and not public.is_assigned_employee(v_row.staff_id) then
    raise exception 'No tienes permiso para modificar esta cita.' using errcode='42501';
  end if;

  update public.appointments
  set status=p_status,
      reminder_status=case when p_status='Cancelada' then 'Cancelado' else reminder_status end
  where id=p_appointment_id returning * into v_row;

  perform public.write_audit(v_row.business_id, 'Cita ' || v_row.confirmation_code || ' actualizada a ' || p_status);
  return v_row;
end;
$$;

create or replace function public.cancel_my_appointment(p_appointment_id bigint)
returns public.appointments
language plpgsql
security definer
set search_path = public
as $$
declare
  v_row public.appointments%rowtype;
begin
  select * into v_row from public.appointments where id=p_appointment_id and client_id=auth.uid();
  if not found then raise exception 'Cita no encontrada.' using errcode='42501'; end if;
  if v_row.status in ('Cancelada','Completada','No asistió') then raise exception 'La cita ya no puede cancelarse.'; end if;
  if v_row.starts_at < now() + interval '2 hours' then raise exception 'La cancelación en línea requiere al menos 2 horas de anticipación.'; end if;

  update public.appointments set status='Cancelada', reminder_status='Cancelado'
  where id=p_appointment_id returning * into v_row;
  perform public.write_audit(v_row.business_id, 'Cita ' || v_row.confirmation_code || ' cancelada por el cliente');
  return v_row;
end;
$$;

create or replace function public.lookup_appointment_by_code(p_code text)
returns table (
  id bigint,
  confirmation_code text,
  status text,
  local_date date,
  local_time time,
  starts_at timestamptz,
  service_id bigint,
  service_name text,
  staff_id bigint,
  staff_name text,
  business_name text,
  business_phone text,
  business_address text
)
language sql
stable
security definer
set search_path = public
as $$
  select a.id, a.confirmation_code, a.status, a.local_date, a.local_time, a.starts_at,
         a.service_id, s.name, a.staff_id, st.name, b.name, b.phone, b.address
  from public.appointments a
  join public.services s on s.id=a.service_id
  join public.staff st on st.id=a.staff_id
  join public.businesses b on b.id=a.business_id
  where upper(a.confirmation_code)=upper(trim(p_code))
  limit 1;
$$;

create or replace function public.log_client_event(p_action text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_business uuid;
begin
  select business_id into v_business from public.profiles where id=auth.uid();
  if v_business is null then
    select id into v_business from public.businesses order by created_at limit 1;
  end if;
  if v_business is not null then perform public.write_audit(v_business,p_action); end if;
end;
$$;

